#!/usr/bin/env python3
"""CLI tool to log in and publish photo additions to Wikipedia across languages.

Supports:
    - Resumable workflows with progress tracking (safe breaks anytime)
    - Terminal image previews using chafa (sixel format)
    - Multi-wiki exploration: discovering linked language pages (ml, te, kn, hi, bn, mr, etc.)
    - Multi-wiki publishing: update Tamil Wikipedia + sibling language wikis in one pass
    - Wikidata Property P18 (image) integration
    - Interactive review with colored diffs
    - Dry-run mode for previewing changes safely

Usage:
    # 1. Preview changes (Dry run) for Tamil Wikipedia:
    python3 update_wiki.py --article "ராமச்சந்திரா" --image "Ramchundra.jpg" --dry-run

    # 2. Resumable interactive review from results.json:
    python3 update_wiki.py --from-file results.json --interactive

    # 3. Interactive review with multi-wiki discovery (check ml, te, kn, hi, etc.):
    python3 update_wiki.py --from-file results.json --interactive --target-wikis indic

    # 4. Update all missing linked language wikis + Wikidata in one click:
    python3 update_wiki.py --from-file results.json --interactive --update-linked-wikis

    # 5. Target a specific language edition (e.g., Malayalam 'ml' or Telugu 'te'):
    python3 update_wiki.py --wiki ml --from-file results.json --interactive
"""

import argparse
import getpass
import json
import os
import sys
from typing import Optional, List, Dict, Any, Set

from wiki_photos.updater import WikiUpdater, TamilWikiUpdater, MultiWikiUpdater
from wiki_photos.preview import show_terminal_image, has_chafa
from wiki_photos.state import UpdateProgressManager
from wiki_photos.wikidata import WikidataClient, INDIC_WIKIS, DRAVIDIAN_WIKIS


def prompt_credentials() -> tuple[str, str]:
    """Get username and password from environment variables or interactive prompt."""
    username = os.environ.get("WIKI_USER")
    password = os.environ.get("WIKI_PASSWORD")

    if not username:
        print("\n[Wikimedia Login]")
        print("Tip: Use a Bot Password (e.g., 'Username@ToolName') created at:")
        print("https://meta.wikimedia.org/wiki/Special:BotPasswords or https://ta.wikipedia.org/wiki/Special:BotPasswords\n")
        username = input("Username (e.g. MyUser@BotName): ").strip()

    if not password:
        password = getpass.getpass("Bot Password: ").strip()

    if not username or not password:
        print("[Error] Username and Bot Password are required.")
        sys.exit(1)

    return username, password


def main():
    parser = argparse.ArgumentParser(
        description="Log in to Wikipedia and update articles with missing photos across language editions.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )

    parser.add_argument(
        "--wiki",
        default="ta",
        help="Primary target wiki language code (default: 'ta' for Tamil Wikipedia)",
    )
    parser.add_argument(
        "--article",
        help="Article title to update (on target --wiki)",
    )
    parser.add_argument(
        "--image",
        help="Image filename (from Commons) to add",
    )
    parser.add_argument(
        "--from-file",
        help="Path to JSON results file generated by find_missing_photos.py",
    )
    parser.add_argument(
        "--interactive",
        action="store_true",
        help="Interactively review image, diff, and confirm each edit before saving",
    )
    parser.add_argument(
        "--update-linked-wikis", "--all-linked-wikis",
        dest="update_linked_wikis",
        action="store_true",
        help="Automatically prompt and update all missing linked language wikis for each article",
    )
    parser.add_argument(
        "--target-wikis",
        default="indic",
        help="Linked languages to check: 'indic' (default: ml, te, kn, hi, bn, mr, etc.), 'all', or comma-separated list like 'ml,te,kn'",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show image and diffs of proposed changes without logging in or modifying Wikipedia",
    )
    parser.add_argument(
        "--summary",
        help="Custom edit summary message (defaults to standard localized summary per wiki)",
    )
    parser.add_argument(
        "-t", "--delay",
        type=float,
        default=1.0,
        help="Delay between edits in seconds (default: 1.0s to respect Wikimedia servers)",
    )
    parser.add_argument(
        "--timeout",
        type=float,
        default=30.0,
        help="HTTP request timeout in seconds (default: 30.0s)",
    )
    parser.add_argument(
        "--maxlag",
        type=int,
        default=5,
        help="Wikimedia maxlag parameter for server load protection (default: 5s)",
    )
    parser.add_argument(
        "--state-file",
        help="Custom path for progress state file (defaults to <from-file>.progress.json)",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="Reset progress state and review from task #1",
    )
    parser.add_argument(
        "--retry-skipped",
        action="store_true",
        help="Re-review articles that were previously skipped",
    )
    parser.add_argument(
        "--image-format",
        choices=["sixel", "symbols", "auto", "none"],
        default="sixel",
        help="Terminal image preview format using chafa (default: sixel)",
    )
    parser.add_argument(
        "--image-size",
        default="45x25",
        help="Terminal preview image size (default: 45x25)",
    )
    parser.add_argument(
        "-w", "--update-wikidata",
        action="store_true",
        help="Also add the photo to Wikidata Property P18 (image) when publishing",
    )
    parser.add_argument(
        "--wikidata-only",
        action="store_true",
        help="Only update Wikidata Property P18 without modifying Wikipedia wikitext",
    )

    args = parser.parse_args()

    # Parse target wikis
    target_wikis: Optional[List[str]] = None
    tw_str = args.target_wikis.lower().strip()
    if tw_str == "all":
        target_wikis = None  # None indicates all linked wikis
    elif tw_str == "indic":
        target_wikis = INDIC_WIKIS
    elif tw_str == "dravidian":
        target_wikis = DRAVIDIAN_WIKIS
    else:
        target_wikis = [w.strip() for w in tw_str.split(",") if w.strip()]

    from wiki_photos.api import MediaWikiClient, DEFAULT_USER_AGENT

    wiki_user = os.environ.get("WIKI_USER")
    ua = (
        f"WikiPhotoFinder/1.1 (https://ta.wikipedia.org/wiki/User:{wiki_user}; Multi-Wiki Photo Tool)"
        if wiki_user
        else DEFAULT_USER_AGENT
    )

    mw_client = MediaWikiClient(
        user_agent=ua,
        request_delay=args.delay,
        timeout=args.timeout,
        maxlag=args.maxlag,
    )
    multi_updater = MultiWikiUpdater(client=mw_client, user_agent=ua)
    primary_updater = multi_updater.get_updater(args.wiki)
    wikidata_client = WikidataClient(client=mw_client)

    # Collect tasks
    tasks: List[Dict[str, Any]] = []
    progress_mgr: Optional[UpdateProgressManager] = None

    if args.from_file:
        state_file = args.state_file or f"{os.path.splitext(args.from_file)[0]}.progress.json"
        progress_mgr = UpdateProgressManager(state_file)

        if args.reset:
            progress_mgr.reset()
            print(f"[i] Progress state reset. Starting fresh for '{args.from_file}'.")

        with open(args.from_file, "r", encoding="utf-8") as f:
            data = json.load(f)
            for item in data:
                tasks.append({
                    "title": item.get(f"{args.wiki}_title") or item.get("ta_title"),
                    "ta_title": item.get("ta_title"),
                    "en_title": item.get("en_title"),
                    "image": item.get("clean_image_name") or item.get("image_name"),
                    "is_commons": item.get("is_on_commons", True),
                    "image_url": item.get("image_url") or item.get("image_thumbnail_url"),
                    "file_page_url": item.get("file_page_url"),
                    "wikidata_id": item.get("wikidata_id"),
                    "wikidata_url": item.get("wikidata_url"),
                    "linked_wikis": item.get("linked_wikis", {}),
                    "missing_wikis": item.get("missing_wikis", []),
                })
    elif args.article and args.image:
        tasks.append({
            "title": args.article,
            "ta_title": args.article if args.wiki == "ta" else None,
            "en_title": None,
            "image": args.image,
            "is_commons": True,
            "image_url": None,
            "file_page_url": f"https://commons.wikimedia.org/wiki/File:{args.image}",
            "wikidata_id": None,
            "wikidata_url": None,
            "linked_wikis": {},
            "missing_wikis": [],
        })
    else:
        parser.print_help()
        print("\n[Error] Please specify either --article and --image, or --from-file <results.json>")
        sys.exit(1)

    if not tasks:
        print("No tasks found to process.")
        return

    # Check progress state for resumable sessions
    total_in_file = len(tasks)
    remaining_tasks: List[Dict[str, Any]] = []

    if progress_mgr:
        prev_updated, prev_skipped = progress_mgr.get_counts()
        for t in tasks:
            if not progress_mgr.is_processed(t["title"], retry_skipped=args.retry_skipped):
                remaining_tasks.append(t)

        print("\n" + "=" * 60)
        print(f"📊 Resumable Session: {args.from_file}")
        print(f"   • Primary Wiki:        {args.wiki}.wikipedia.org")
        print(f"   • Total tasks in file: {total_in_file}")
        print(f"   • Previously updated:  {prev_updated}")
        print(f"   • Previously skipped:  {prev_skipped}")
        print(f"   • Remaining to review: {len(remaining_tasks)}")
        print(f"   • Progress file:       {progress_mgr.state_file}")
        print("=" * 60)

        if not remaining_tasks:
            print("\n[✓] All articles in this file have already been processed!")
            print("Tip: Use --retry-skipped to re-examine skipped items, or --reset to restart.")
            return
    else:
        remaining_tasks = tasks

    # Check login (only if not dry run)
    username: Optional[str] = None
    password: Optional[str] = None
    if not args.dry_run:
        username, password = prompt_credentials()
        multi_updater.set_credentials(username, password)
        print(f"[*] Logging in to {args.wiki}.wikipedia.org as '{username}'...")
        try:
            primary_updater.login(username, password)
            print(f"[✓] Logged in successfully as {primary_updater.logged_in_user}!")
        except Exception as e:
            print(f"[✗] Login failed on {args.wiki}.wikipedia.org: {e}")
            sys.exit(1)
    else:
        print("[*] Running in DRY-RUN mode. No edits will be published.")

    # Process tasks
    session_updated = 0
    session_skipped = 0

    try:
        for idx, task in enumerate(remaining_tasks, 1):
            title = task["title"]
            image = task["image"]
            is_commons = task.get("is_commons", True)
            img_url = task.get("image_url")
            file_url = task.get("file_page_url")
            qid = task.get("wikidata_id")

            # Resolve QID if missing
            if not qid:
                try:
                    pinfo = mw_client.get_pages_info(args.wiki, [title])
                    qid = pinfo.get(title, {}).get("wikidata_id")
                except Exception:
                    pass

            print("\n" + "─" * 60)
            print(f"[{idx}/{len(remaining_tasks)}] Article: {title} ({args.wiki}.wikipedia.org)")
            print(f"    Photo:   {image} (Commons: {'Yes' if is_commons else 'Local enwiki'})")
            if file_url:
                print(f"    Page:    {file_url}")

            # Check Wikidata P18 status
            has_p18 = False
            p18_img = None
            if qid:
                try:
                    has_p18, p18_img = wikidata_client.has_p18_image(qid)
                    if has_p18:
                        print(f"    Wikidata: {qid} (P18: Already present: '{p18_img}')")
                    else:
                        print(f"    Wikidata: {qid} (\033[93mP18: Missing on Wikidata! Can be added\033[0m)")
                except Exception:
                    print(f"    Wikidata: {qid}")

            if not is_commons:
                print("    [Warning] This photo is hosted locally on English Wikipedia.")
                print("    It must be uploaded to Commons before embedding in other wikis.")
                if progress_mgr:
                    progress_mgr.mark_skipped(title, image, "local_enwiki_only")
                session_skipped += 1
                continue

            # Render Sixel / Terminal image preview
            if img_url and args.image_format != "none":
                if has_chafa():
                    print("\n[🖼️ Photo Preview (Sixel)]")
                    rendered = show_terminal_image(
                        image_url=img_url,
                        user_agent=ua,
                        image_format=args.image_format,
                        size=args.image_size,
                    )
                    if not rendered:
                        print("  (Preview could not be rendered in this terminal)")
                else:
                    print("  (Tip: install 'chafa' for in-terminal sixel image previews)")

            # Check linked wikis for this article
            linked_titles: Dict[str, str] = {}
            if qid:
                try:
                    all_sitelinks = wikidata_client.get_entity_sitelinks(qid, target_wikis=target_wikis)
                    linked_titles = {k: v for k, v in all_sitelinks.items() if k != "en"}
                except Exception:
                    pass

            # Inspect photo presence on linked wikis
            linked_missing: Dict[str, str] = {}
            linked_present: Dict[str, str] = {}
            for l_wiki, l_title in linked_titles.items():
                if l_wiki == args.wiki:
                    continue
                try:
                    pinfo = mw_client.get_pages_info(l_wiki, [l_title])
                    pdata = pinfo.get(l_title, {})
                    if pdata.get("has_image"):
                        linked_present[l_wiki] = l_title
                    elif not pdata.get("missing"):
                        linked_missing[l_wiki] = l_title
                except Exception:
                    pass

            if linked_titles:
                print("\n    🌐 Linked Language Wikis:")
                if linked_missing:
                    missing_str = ", ".join([f"\033[91m{w}\033[0m ({t})" for w, t in linked_missing.items()])
                    print(f"       Missing photo: {missing_str}")
                if linked_present:
                    present_str = ", ".join([f"\033[92m{w}\033[0m ({t})" for w, t in linked_present.items()])
                    print(f"       Already has photo: {present_str}")

            # Fetch primary wiki content
            content, revid = primary_updater.get_page_content(title)
            primary_exists = content is not None
            primary_has_image = bool(content and image in content)

            if not primary_exists:
                print(f"    [Warning] Page '{title}' does not exist on {args.wiki}.wikipedia.org.")

            # Wikitext diff on primary wiki
            new_content = None
            if primary_exists and not primary_has_image:
                new_content = primary_updater.apply_image_to_wikitext(content, title, image, wiki=args.wiki)
                diff = primary_updater.generate_diff(content, new_content, title)
                print(f"\n--- Proposed Wikitext Diff ({args.wiki}.wikipedia.org: {title}) ---")
                for line in diff.splitlines():
                    if line.startswith("+") and not line.startswith("+++"):
                        print(f"\033[92m{line}\033[0m")
                    elif line.startswith("-") and not line.startswith("---"):
                        print(f"\033[91m{line}\033[0m")
                    else:
                        print(line)
                print("-------------------------------------------------------")
            elif primary_has_image:
                print(f"    [Info] Image '{image}' is already present on {args.wiki}.wikipedia.org.")

            can_wikidata = bool(qid and not has_p18 and is_commons)
            has_other_missing = bool(linked_missing)

            # Determine available actions
            all_missing_wikis: Dict[str, str] = {}
            if primary_exists and not primary_has_image:
                all_missing_wikis[args.wiki] = title
            all_missing_wikis.update(linked_missing)

            # Interactive Prompt
            action = "single"
            chosen_wikis: List[str] = []
            update_wd = args.update_wikidata

            if args.wikidata_only:
                action = "wikidata"
            elif args.update_linked_wikis:
                action = "all"
                update_wd = True
            elif args.interactive:
                while True:
                    prompt_options = []
                    if primary_exists and not primary_has_image:
                        prompt_options.append(f"[y]es ({args.wiki})")
                    if has_other_missing:
                        prompt_options.append(f"[a]ll missing ({', '.join(all_missing_wikis.keys())})")
                        prompt_options.append("[c]hoose wikis")
                    if can_wikidata:
                        prompt_options.append("[w]ikidata only")
                        prompt_options.append(f"[b]oth ({args.wiki}+wikidata)")
                    prompt_options.extend(["[n]o (skip)", "[p]review", "[q]uit"])

                    prompt_str = f"Publish edit? {' / '.join(prompt_options)}: "
                    choice = input(prompt_str).strip().lower()

                    if choice == "p":
                        if img_url:
                            show_terminal_image(img_url, user_agent=ua, image_format=args.image_format, size=args.image_size)
                        continue
                    elif choice == "q":
                        print(f"\n[i] Session paused. Progress saved to {progress_mgr.state_file if progress_mgr else 'state'}.")
                        print("    You can resume anytime by running the same command!")
                        return
                    elif choice in ("a", "all") and all_missing_wikis:
                        action = "all"
                        chosen_wikis = list(all_missing_wikis.keys())
                        update_wd = can_wikidata
                        break
                    elif choice in ("c", "choose") and all_missing_wikis:
                        action = "choose"
                        avail = ", ".join(all_missing_wikis.keys())
                        c_input = input(f"Enter wikis to update (available: {avail}): ").strip().lower()
                        chosen_wikis = [w.strip() for w in c_input.split(",") if w.strip() in all_missing_wikis]
                        update_wd = can_wikidata
                        break
                    elif choice in ("w", "wikidata") and can_wikidata:
                        action = "wikidata"
                        break
                    elif choice in ("b", "both"):
                        action = "single"
                        chosen_wikis = [args.wiki] if (primary_exists and not primary_has_image) else []
                        update_wd = can_wikidata
                        break
                    elif choice in ("y", "yes"):
                        action = "single"
                        chosen_wikis = [args.wiki] if (primary_exists and not primary_has_image) else []
                        update_wd = args.update_wikidata and can_wikidata
                        break
                    elif choice in ("n", "no", ""):
                        action = "skip"
                        break
                    else:
                        print("Invalid option. Please choose from the available actions.")

                if action == "skip":
                    print(f"Skipped '{title}'.")
                    if progress_mgr:
                        progress_mgr.mark_skipped(title, image, "skipped_by_user")
                    session_skipped += 1
                    continue
            else:
                # Non-interactive default: target wiki + optional wikidata
                chosen_wikis = [args.wiki] if (primary_exists and not primary_has_image) else []

            if action == "all":
                chosen_wikis = list(all_missing_wikis.keys())
            elif action == "single" and not chosen_wikis and primary_exists and not primary_has_image:
                chosen_wikis = [args.wiki]

            # Execute Updates
            updated_any = False

            # 1. Update Wikidata Property P18
            if (update_wd or action == "wikidata") and qid and not has_p18 and is_commons:
                print(f"Adding photo to Wikidata item '{qid}' (Property P18)...")
                if not args.dry_run:
                    try:
                        if not wikidata_client.logged_in_user:
                            wikidata_client.login(username, password)
                        wikidata_client.add_p18_image(qid, image)
                        print(f"[✓] Added P18 to Wikidata: https://www.wikidata.org/wiki/{qid}")
                        updated_any = True
                    except Exception as e:
                        print(f"[✗] Failed to update Wikidata for '{qid}': {e}")
                else:
                    print(f"[Dry-run] Would add P18 '{image}' to https://www.wikidata.org/wiki/{qid}")
                    updated_any = True

            # 2. Update Selected Wikipedia Editions
            for w in chosen_wikis:
                w_title = all_missing_wikis.get(w)
                if not w_title:
                    continue

                w_updater = multi_updater.get_updater(w)
                w_content, w_revid = w_updater.get_page_content(w_title)
                if not w_content:
                    print(f"    [Error] Page '{w_title}' not found on {w}.wikipedia.org")
                    continue

                w_new_content = w_updater.apply_image_to_wikitext(w_content, w_title, image, wiki=w)

                if args.dry_run:
                    w_diff = w_updater.generate_diff(w_content, w_new_content, w_title)
                    print(f"\n[Dry-run] Diff for {w}.wikipedia.org: {w_title}")
                    for line in w_diff.splitlines():
                        if line.startswith("+") and not line.startswith("+++"):
                            print(f"\033[92m{line}\033[0m")
                        elif line.startswith("-") and not line.startswith("---"):
                            print(f"\033[91m{line}\033[0m")
                        else:
                            print(line)
                    print(f"[Dry-run] Would publish edit to '{w_title}' on {w}.wikipedia.org")
                    updated_any = True
                else:
                    try:
                        print(f"Publishing edit to '{w_title}' on {w}.wikipedia.org...")
                        w_resp = w_updater.edit_page(
                            title=w_title,
                            new_content=w_new_content,
                            summary=args.summary,
                            baserevid=w_revid,
                        )
                        new_revid = w_resp.get("newrevid")
                        print(f"[✓] Published to {w}.wikipedia.org! (Revision: {new_revid or 'ok'})")
                        updated_any = True
                    except Exception as e:
                        print(f"[✗] Failed to edit '{w_title}' on {w}.wikipedia.org: {e}")

            if updated_any:
                if progress_mgr and not args.dry_run:
                    progress_mgr.mark_updated(title, image, f"wikis:{','.join(chosen_wikis)}")
                session_updated += 1
            else:
                if progress_mgr and not args.dry_run:
                    progress_mgr.mark_skipped(title, image, "no_edits_made")
                session_skipped += 1

    except KeyboardInterrupt:
        print("\n\n[!] Interrupted by user (Ctrl+C).")
        if progress_mgr:
            print(f"[i] Progress saved to '{progress_mgr.state_file}'. You can resume anytime!")

    # Summary
    print("\n" + "=" * 60)
    print("Session Summary:")
    print(f"  • Updated this session: {session_updated}")
    print(f"  • Skipped this session: {session_skipped}")
    if progress_mgr:
        total_up, total_sk = progress_mgr.get_counts()
        print(f"  • Overall completed:   {total_up} updated, {total_sk} skipped out of {total_in_file} total.")
    print("=" * 60)


if __name__ == "__main__":
    main()
