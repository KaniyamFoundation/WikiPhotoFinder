def format_markdown(results: List[ArticleResult], category_name: str) -> str:
    """Format results as a GitHub Flavored Markdown report."""
    has_linked = any(r.linked_wikis for r in results)
    headers = ["#", "Tamil Article", "English Article", "Photo", "Commons?", "Quick Wikitext Snippet"]
    alignments = ["|:---:", "|---|", "|---|", "|---|", "|:---:|", "|---|"]
    if has_linked:
        headers.append("Also Missing")
        alignments.append("|---|")

    md = [
        f"# Missing Photos in Tamil Wikipedia",
        f"",
        f"**Category:** `{category_name}`  ",
        f"**Articles Found:** {len(results)}  ",
        f"",
        f"| {' | '.join(headers)} |",
        "".join(alignments),
    ]

    for idx, r in enumerate(results, 1):
        ta_link = f"[{r.ta_title}]({r.ta_url})"
        en_link = f"[{r.en_title}]({r.en_url})"
        img_link = f"[{r.clean_image_name}]({r.file_page_url})"
        commons_badge = "✅ Yes" if r.is_on_commons else "⚠️ Local (en)"
        snippet = f"`{r.wikitext_snippet}`"
        row = [str(idx), ta_link, en_link, img_link, commons_badge, snippet]
        if has_linked:
            sibling_missing = [w for w in r.missing_wikis if w != "ta"]
            row.append(", ".join(sibling_missing) if sibling_missing else "None")

        md.append(f"| {' | '.join(row)} |")

    md.append("")
    md.append("---")
    md.append("*Generated by WikiPhotoFinder tool.*")
    return "\n".join(md)


def format_csv(results: List[ArticleResult]) -> str:
    """Format results as CSV."""
    has_linked = any(r.linked_wikis for r in results)
    output = io.StringIO()
    writer = csv.writer(output)
    headers = [
        "Index",
        "Tamil Title",
        "Tamil URL",
        "English Title",
        "English URL",
        "Image Name",
        "Is on Commons",
        "Image URL",
        "File Page URL",
        "Wikidata ID",
        "Wikitext Snippet",
        "Infobox Snippet",
    ]
    if has_linked:
        headers.extend(["Missing Linked Wikis", "Present Linked Wikis"])

    writer.writerow(headers)

    for idx, r in enumerate(results, 1):
        row = [
            idx,
            r.ta_title,
            r.ta_url,
            r.en_title,
            r.en_url,
            r.clean_image_name,
            "Yes" if r.is_on_commons else "No",
            r.image_url or "",
            r.file_page_url,
            r.wikidata_id or "",
            r.wikitext_snippet,
            r.infobox_snippet,
        ]
        if has_linked:
            row.append(", ".join(r.missing_wikis))
            row.append(", ".join(r.present_wikis))
        writer.writerow(row)

    return output.getvalue()


def format_json(results: List[ArticleResult], indent: int = 2) -> str:
    """Format results as JSON string."""
    data = [r.to_dict() for r in results]
    return json.dumps(data, ensure_ascii=False, indent=indent)


