def print_rich_table(results: List[ArticleResult], category_name: str) -> None:
    """Print results using Rich table for beautiful terminal rendering."""
    has_linked = any(r.linked_wikis for r in results)
    try:
        from rich.console import Console
        from rich.table import Table
        from rich import box

        console = Console()
        table = Table(
            title=f"Tamil Wikipedia Articles Missing Photos (Category: {category_name})",
            box=box.ROUNDED,
            header_style="bold cyan",
        )

        table.add_column("#", style="dim", justify="right")
        table.add_column("Tamil Article", style="bold green")
        table.add_column("English Article", style="blue")
        table.add_column("Photo (English/Commons)", style="magenta")
        table.add_column("Commons?", justify="center")
        if has_linked:
            table.add_column("Also Missing In", style="red")
        table.add_column("Wikitext to Add", style="yellow")

        for idx, r in enumerate(results, 1):
            commons_str = "[bold green]Yes[/]" if r.is_on_commons else "[yellow]Local(en)[/]"
            row = [
                str(idx),
                r.ta_title,
                r.en_title,
                r.clean_image_name,
                commons_str,
            ]
            if has_linked:
                siblings = [w for w in r.missing_wikis if w != "ta"]
                row.append(", ".join(siblings) if siblings else "[dim]None[/]")
            row.append(r.wikitext_snippet)
            table.add_row(*row)

        console.print(table)
    except ImportError:
        # Fallback to plain print
        print(f"\nMissing Photos in Tamil Wikipedia (Category: {category_name}):")
        if has_linked:
            print(f"{'#':<4} {'Tamil Article':<24} {'English Article':<24} {'Commons':<8} {'Also Missing':<16} {'Photo'}")
            print("-" * 95)
            for idx, r in enumerate(results, 1):
                commons_str = "Yes" if r.is_on_commons else "No(en)"
                siblings = ", ".join([w for w in r.missing_wikis if w != "ta"]) or "None"
                print(f"{idx:<4} {r.ta_title:<24} {r.en_title:<24} {commons_str:<8} {siblings:<16} {r.clean_image_name}")
        else:
            print(f"{'#':<4} {'Tamil Article':<28} {'English Article':<28} {'Commons':<8} {'Photo'}")
            print("-" * 80)
            for idx, r in enumerate(results, 1):
                commons_str = "Yes" if r.is_on_commons else "No(en)"
                print(f"{idx:<4} {r.ta_title:<28} {r.en_title:<28} {commons_str:<8} {r.clean_image_name}")
